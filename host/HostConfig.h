// HostConfig: everything that differs between the Disney games built on the Rapture engine (Moses/Aaron) in the HOST program (the exe that is the same code in
// Shoot.exe, Flying.exe, Quest.exe, Ruckus.exe, see docs/REUSE.md sec. 1.3) and in the files around it.  The shared engine
// (platform, moses, aaron, arcade, host, autoplay, tests) contains no game name: each game fills one HostConfig (a plain struct of
// constants, game/HostConfig<Game>.cpp) and passes it to HostMain().
//
// What the original hardcodes per game (Shoot.exe, measured in docs/REUSE.md sec. 1.3):
//   * LoadStringA ids of the title / of the game name in the registry key  (.text immediates 0x1b83, 0x1bdb)
//   * the id of the title picture sprite (0x658b00xx)                       (.text immediate 0x9497)
//   * .data strings: scene DLL name, FX archive name
//   * the RT_STRING table itself (identical in the four games, so the generated table can be shared; it is still supplied by
//     the game so that the engine contains no data of any game)
// Port additions: settings ini location (the registry replacement), archive names for the tests, game-specific tests and
// autoplay commands, the function that creates the game scene.
#pragma once

#include "aaron/Types.h"
#include "arcade/ArcadeTypes.h"

namespace autoplay {
class Extension;
}

namespace rapture {

using aaron::u32;

// One entry of the host exe's RT_STRING table (generated by tools/extract_host_strings.py into a .inc the game includes).
struct StringEntry {
    u32 id;
    const char* text;
};

// A data file of the game used by the platform / engine tests (--rrs-test, --engine-test 2).
struct DataFile {
    const char* file;   // "mus.rrs"
    bool hasStrings;    // the archive holds the string records (Pkg2 test expects them)
};

// A game-specific headless test: `--game-test <name>`.
struct GameTest {
    const char* name;
    int (*run)(int argc, char** argv);   // argv[0] = name, as RunArcadeTests / RunHostTests
};

struct HostConfig {
    // ---- identity ---------------------------------------------------------------------------------------------------
    const char* productName = "";            // short name: --movie window title, messages
    const char* defaultTitle = "";           // window title when `titleStrId` is not in the string table

    // ---- the host exe's string table and the ids that pick this game's strings --------------------------------------
    const StringEntry* strings = nullptr;
    int stringCount = 0;
    u32 titleStrId = 0;                      // LoadStringA id of the window title                (Shoot.exe: 0x5014)
    u32 registryNameStrId = 0;               // id of the game-name component of the registry key    (Shoot.exe .text +0x1bdb: 0x501a)
    const char* registryNameFallback = "";   // used when the id is missing from the table

    // ---- settings (the port's replacement for HKCU\Software\Disney Interactive\...) ---------------------------------
    // %APPDATA%\<folder>\<file> (Linux: $XDG_CONFIG_HOME/<folder>/<file>); --settings FILE overrides it.  The registry key
    // (APPINIT.regKey) is built from the string table: <vendor 0x5017>\<registryNameStrId>\<locale 0x501d>.
    const char* settingsFolder = "";
    const char* settingsFile = "";

    // ---- scenes -----------------------------------------------------------------------------------------------------
    const char* hostBinary = "";             // name of the module that holds the Title scene       ("Shoot.exe")
    const char* sceneDll = "";               // the game's scene DLL, as GetModule() receives it   (Shoot.exe .data: the scene DLL)
    const char* sceneEntry = "CreateScene";  // its export                                         ("CreateScene")
    aaron::CreateSceneFn createGameScene = nullptr;   // the port's CreateScene of the game; registered as (sceneDll, sceneEntry)
    u32 titleSpriteId = 0;                   // the title picture in the common strings archive    (0x658b0025)

    // ---- archives (Scene::OpenArchive slot numbers 100 / 0x65 are engine constants, see kSlotCommon*) ---------------
    const char* commonArchive = "";          // AVIs + credits background, identical in all games   (Shoot.exe: slot 100)
    const char* commonStringsArchive = "";   // strings, title picture, credits text                (Shoot.exe: slot 0x65)
    const char* fxArchive = "";              // sound/music of the game, opened by the second Title visit (Shoot.exe .data)
    int fxSlot = 1;
    const char* mainArchive = "";            // the game's picture archive ("mus.rrs"): its presence marks the game folder

    // ---- tests / autoplay -------------------------------------------------------------------------------------------
    const DataFile* dataFiles = nullptr;     // all archives (for --rrs-test / --engine-test 2); may be empty
    int dataFileCount = 0;
    const char* const* movies = nullptr;     // AVI files of the game folder (for --rrs-test)
    int movieCount = 0;
    const GameTest* gameTests = nullptr;     // `--game-test <name>` of the game itself (arcade / host are the engine's)
    int gameTestCount = 0;
    const ArcadeGameDef* arcadeDef = nullptr; // the game's own Arcade definition (DAT_10031ae0 in Shoot.dll): --game-test host opens the
                                              // popups on a headless game scene built from it; may be null (those tests are skipped)
    autoplay::Extension* autoplay = nullptr; // game-specific --autoplay commands (autoplay/Autoplay.h); may be null
};

// The archive slots the Host uses (Shoot.exe: Scene::OpenArchive(100, ...) / (0x65, ...)).
constexpr int kSlotCommon = 100;
constexpr int kSlotCommonStrings = 0x65;
// String ids shared by the four games (the same in every RT_STRING table).
constexpr u32 kStrVendorKey = 0x5017;        // "Software\Disney Interactive"
constexpr u32 kStrLocale = 0x501d;           // "US" / "IT": last component of the registry key

// The configuration in use.  HostMain() / RunHost() install it; tests may install their own (nullptr = defaults of an
// empty HostConfig).  Never null.
const HostConfig& Config();
void SetConfig(const HostConfig* cfg);

} // namespace rapture
