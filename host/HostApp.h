// G2 - HostApp: the application object of the host exe (= CShootApp in Shoot.exe: 0x668 bytes, vtable 0x415360, base CAaronApp =
// Aaron Application).  The neutral name is the port's; Flying.exe / Quest.exe / Ruckus.exe have the same class.
// Shoot.exe 0x401000-0x401d00 (+ WinMain 0x401b6f).  Per-game differences come from HostConfig (host/HostConfig.h).
//
// What it adds to Aaron's Application:
//   * LoadString (original "GetString" 0x4010ab): the localized strings come from the exe's own RT_STRING table
//     (id + 0x5006).  The port has the table compiled into the game (HostConfig::strings, generated by tools/extract_host_strings.py).
//   * OnDestroy (original "OnExit" 0x401a3c): saves WaveVol / MidiVol, then Application::OnDestroy.
//   * LoadScene (original "OnStart" 0x401a71): loads WaveVol / MidiVol, then Application::LoadScene.
//   * CreateObject (0x40127a, vtable slot 0x38): the popup factory = G1's IPopupFactory.  Shoot.dll reaches it with
//     Application::GetApp() + a virtual call; the port registers it once with SetPopupFactory.
//   * FeedKeySequences (0x401aac, slot 0x3c): the two "secret key" sequences (strings 0x658c0006 / 0x658c0007 of the common strings archive).
#pragma once

#include "aaron/Application.h"
#include "arcade/ArcadeTypes.h"

namespace rapture {

// What FeedKeySequences feeds: in the original `listener->vtbl[7](seqId, key, first)` (a Controller/player input object of
// Shoot.dll).  The port's Controller has no key-sequence support, so the sink is an interface the game (G3) can implement.
class IKeySequenceSink {
public:
    virtual ~IKeySequenceSink() = default;
    virtual void AddKeySequenceKey(int seqId /*0x10 or 0x20*/, char key, bool first) = 0;
};

class HostApp : public aaron::Application, public IPopupFactory {
public:
    // Shoot.exe 0x401000.  (The 0x450..0x668 zeroing is the two key sequence buffers.)
    explicit HostApp(const aaron::APPINIT* init);
    ~HostApp() override;                                           // 0x401043

    // The APPINIT WinMain builds from Config(): title = string titleStrId, registry key =
    // <string 0x5017> + '\\' + <registryNameStrId> + '\\' + <string 0x501d> (Shoot.exe: "Software\Disney Interactive\...\IT"),
    // scene = the Title screen of this exe.
    static void BuildAppInit(aaron::APPINIT& out);

    // ---- string table ---------------------------------------------------------------------------------------
    // Raw entry of Config().strings by resource id (0x5007..0x501d); nullptr if missing.
    static const char* ResourceString(u32 resId);
    static int ResourceStringCount();
    // 0x4010ab.  `id` is the Aaron-level id (resource = id + 0x5006).  Falls back to Application::LoadString.
    // Resource 0x5010 is a format that takes the application title ("%s requires 256 colours or more").
    int LoadString(u32 id, char* buf, int len) override;

    // ---- life cycle ---------------------------------------------------------------------------------------------
    void OnDestroy() override;                                        // 0x401a3c "OnExit"
    void LoadScene(aaron::Module* module) override;                   // 0x401a71 "OnStart"

    // ---- key sequences -----------------------------------------------------------------------------------------
    void SetKeySequence(int seqId, const char* keys);                 // 0x401069 (0x10 -> buffer A, 0x20 -> buffer B)
    bool FeedKeySequences(IKeySequenceSink* sink);                    // 0x401aac (false if sink == nullptr)
    const char* KeySequence(int seqId) const { return seqId == 0x10 ? keySeqA_ : (seqId == 0x20 ? keySeqB_ : ""); }

    // ---- popups -------------------------------------------------------------------------------------------------
    // 0x40127a.  parent == nullptr -> the root widget of the application's current scene.  Returns the created popup
    // (an aaron::Widget*) or nullptr (unknown type / creation failed: the popup is deleted by InitOrDelete).
    void* CreateObject(void* parent, int type, uintptr_t arg) override;
    // 0x40114c.  modal != 0: the application quits when the credits end (or if they cannot be created).
    aaron::Widget* CreateCredits(uintptr_t modal, aaron::Widget* parent);

    // Port addition for headless tests: scene used as parent when the application has no current scene.
    void SetFallbackScene(aaron::Scene* s) { fallbackScene_ = s; }

private:
    aaron::Widget* DefaultParent() const;
    char keySeqA_[0xff] = {0};      // +0x468
    char keySeqB_[0xff] = {0};      // +0x567
    aaron::Scene* fallbackScene_ = nullptr;
};

// DAT_00418e10: the one HostApp (WinMain); nullptr outside RunHost.
HostApp* TheHostApp();

// Shoot.exe WinMain 0x401b6f: builds the HostApp from Config(), registers the game scene + the popup factory and runs it.  Returns the exit code.
// `cmdline` is the Aaron command line (bare argument = scene dll; normally empty).
int RunHost(const char* cmdline);

} // namespace rapture
