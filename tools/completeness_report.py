def parse_qmsg_ops(engine):
    """-> [(name, value, comment)] from moses/QueueMsg.h (enum QMSG_OP)"""
    path = os.path.join(engine, 'moses', 'QueueMsg.h')
    ops = []
    if not os.path.exists(path):
        return ops
    text = open(path, encoding='utf-8', errors='replace').read()
    m = re.search(r'enum QMSG_OP[^{]*\{(.*?)\n\};', text, re.S)
    if not m:
        return ops
    for ln in m.group(1).split('\n'):
        parts = ln.split('//', 1)
        code = parts[0]
        com = parts[1].strip() if len(parts) > 1 else ''
        for nm, val in re.findall(r'(QM_[A-Z0-9_]+)\s*=\s*(0x[0-9a-fA-F]+|\d+)', code):
            ops.append((nm, int(val, 0), com))
    return ops


def effective(r):
    st = r['st']
    if st == 'yes':
        return 'implemented'
    if st == 'n.a.':
        return 'n.a.'
    if not r['users'] and not r.get('aaron_uses'):
        return 'unused'
    return 'partial' if st == 'partial' else 'missing'


def write_completeness(path, engine, games, short, mrows, arows, mark):
    if not os.path.exists(path):
        print('COMPLETENESS: %s not found, skipped' % path)
        return
    gl = list(games)
    L = []
    w = L.append
    cm = collections.Counter(effective(r) for r in mrows)
    ca = collections.Counter(effective(r) for r in arows)
    w('Generated by `engine/tools/engine_coverage.py` on %s: **do not edit by hand** (re-run the script).' % datetime.date.today().isoformat())
    w("Statuses: `implemented` = present in the port (the original address is in a `.cpp`, or the reference game uses it); `partial` = only")
    w('declared / to be verified; `missing` = used by at least one game of the family but absent from the port; `unused` = no game of the family')
    w("imports it (for moses, not even Aaron): only needed for completeness (future editor); `n.a.` = compiler artefact.")
    w('')
    w('### Summary')
    w('')
    w('| category | total | implemented | partial | missing | unused | n.a. |')
    w('|---|---:|---:|---:|---:|---:|---:|')
    w('| moses.dll exports | %d | %d | %d | %d | %d | %d |' % (len(mrows), cm['implemented'], cm['partial'], cm['missing'], cm['unused'], cm['n.a.']))
    w('| Aaron.dll ordinals | %d | %d | %d | %d | %d | %d |' % (len(arows), ca['implemented'], ca['partial'], ca['missing'], ca['unused'], ca['n.a.']))
    ops = parse_qmsg_ops(engine)
    srcs = ''
    for root, _, names in os.walk(os.path.join(engine, 'moses')):
        for n in names:
            if n.endswith('.cpp'):
                srcs += open(os.path.join(root, n), encoding='utf-8', errors='replace').read()
    qrows = [(nm, val, com, 'implemented' if re.search(r'\b' + nm + r'\b', srcs) else 'missing') for nm, val, com in ops]
    cq = collections.Counter(r[3] for r in qrows)
    w('| QUEUEMSG opcodes (common 1..15, class-specific >= 100) | %d | %d | 0 | %d | 0 | 0 |' % (len(qrows), cq['implemented'], cq['missing']))
    cr = collections.Counter(r[4] for r in RES_TYPES)
    w('| `.rrs` resource types | %d | %d | 0 | %d | %d | 0 |' % (len(RES_TYPES), cr['implemented'], cr['missing'], cr['unused']))
    ci = collections.Counter(r[4] for r in INI_OPTIONS)
    w('| `rapture.ini` options | %d | %d | 0 | %d | %d | 0 |' % (len(INI_OPTIONS), ci['implemented'], ci['missing'], ci['unused']))
    w('')
    w('Columns `used by`: ' + ', '.join('%s=%s' % (short.get(g, g[0]), g) for g in gl) + '; a dot = not imported.')
    w('')
    w('### To do: `missing` and `partial` exports/ordinals (used by at least one game)')
    w('')
    w('| kind | ord | address | name | status | used by |')
    w('|---|---:|---|---|---|---|')
    n = 0
    for r in mrows:
        if effective(r) in ('missing', 'partial'):
            n += 1
            w('| moses | %d | `0x%08x` | `%s` | %s | %s |' % (r['ord'], r['addr'], r['dem'].replace('|', '\\|'), effective(r), mark(r['users'], gl)))
    for r in arows:
        if effective(r) in ('missing', 'partial'):
            n += 1
            w('| Aaron | %d | `0x%08x` | %s | %s | %s |' % (r['ord'], r['addr'], '`%s`' % r['name'] if r['name'] else 'to be analysed', effective(r), mark(r['users'], gl)))
    if not n:
        w('| (none) | | | | | |')
    w('')
    w('### moses.dll exports not `implemented` (full list; the `implemented` ones are in `ENGINE_API_COVERAGE.md` section 3)')
    w('')
    w('| ord | address | name | status | used by | used by Aaron |')
    w('|---:|---|---|---|---|---|')
    for r in mrows:
        e = effective(r)
        if e in ('missing', 'partial', 'unused'):
            w('| %d | `0x%08x` | `%s` | %s | %s | %s |' % (r['ord'], r['addr'], r['dem'].replace('|', '\\|'), e, mark(r['users'], gl), 'x' if r['aaron_uses'] else ''))
    w('')
    w('### Aaron.dll ordinals not `implemented` (full list)')
    w('')
    w('| ord | address | name | status | used by |')
    w('|---:|---|---|---|---|')
    for r in arows:
        e = effective(r)
        if e in ('missing', 'partial', 'unused'):
            w('| %d | `0x%08x` | %s | %s | %s |' % (r['ord'], r['addr'], '`%s`' % r['name'] if r['name'] else 'to be analysed', e, mark(r['users'], gl)))
    w('')
    w('### QUEUEMSG opcodes (`moses/QueueMsg.h`; 1..15 handled by `CAnimObj`, >= 100 by the class `process_message_hook`)')
    w('')
    w('| opcode | value | meaning | status |')
    w('|---|---:|---|---|')
    for nm, val, com, st in qrows:
        w('| `%s` | %d | %s | %s |' % (nm, val, com.replace('|', '/'), st))
    w('')
    w('Values >= 100 are reused by different classes (`CAnimDib` 100..103, `CAnimRect` "iris" 100..105); `CAnimText/Poly/Meta` have no opcodes of their own.')
    w("Which opcodes the tables of each game use has not been measured yet (WP-6).")
    w('')
    w('### `.rrs` resource types')
    w('')
    w('| type | meaning | original handler | constant in the port | status | note |')
    w('|---:|---|---|---|---|---|')
    for t, mean, hand, const, st, note in RES_TYPES:
        w('| %d | %s | `%s` | `%s` | %s | %s |' % (t, mean, hand, const, st, note))
    w('')
    w('### `rapture.ini` options (read by `IniGetInt` in moses.dll; file in the current folder)')
    w('')
    w('| section | key | where | effect | status | note |')
    w('|---|---|---|---|---|---|')
    for sec, key, where, effect, st, note in INI_OPTIONS:
        w('| `[%s]` | `%s` | `%s` | %s | %s | %s |' % (sec, key, where, effect, st, note))
    w('')
    text = open(path, encoding='utf-8').read()
    if BEGIN not in text or END not in text:
        print('COMPLETENESS: markers missing in', path)
        return
    text = text[:text.index(BEGIN) + len(BEGIN)] + '\n' + '\n'.join(L) + '\n' + text[text.index(END):]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('written', path)
