# Extracts the RT_STRING table (language IT 0x410, otherwise the first available) of a game's HOST exe
# (Shoot.exe, Flying.exe, Quest.exe, Ruckus.exe: same code, same 23 ids 0x5007..0x501d) into a .inc file that the game includes
# in its HostConfig (HostConfig::strings, see engine/host/HostConfig.h).
#
# Usage:  python -I engine/tools/extract_host_strings.py <HOST.exe> <OUT.inc> [LANGID_HEX]
#   e.g.  python -I engine/tools/extract_host_strings.py "../Shoot.exe" game/Strings.inc
# (it works on any exe of the family. LANGID_HEX default 410 = Italian.)
# Standard library only (uses pe_resources.py next to this script); no pefile needed.
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe_resources import PEResources

BS = chr(92)


def main(exe, out, want=0x410):
    best = PEResources(exe).string_table(want)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by engine/tools/extract_host_strings.py (RT_STRING of ' + os.path.basename(exe) + ', IT). Do not edit by hand.\n')
        for sid in sorted(best):
            esc = best[sid].replace(BS, BS + BS).replace('"', BS + '"').replace('\n', BS + 'n').replace('\r', BS + 'r')
            f.write('{0x%x, "%s"},\n' % (sid, esc))
    print(len(best), 'strings')


main(sys.argv[1], sys.argv[2], int(sys.argv[3], 16) if len(sys.argv) > 3 else 0x410)
